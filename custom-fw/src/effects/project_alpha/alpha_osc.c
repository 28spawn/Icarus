/* custom-fw/src/effects/project_alpha/alpha_osc.c — Band-Limited Dual Oscillator + Sub Oscillator Engine */
#include "alpha_osc.h"
#include "pa_config.h"
#include <math.h>

#define ALPHA_FS     ((float)PA_SAMPLE_RATE)
#define ALPHA_INV_FS (1.0f / (float)PA_SAMPLE_RATE)

static inline float clampf(float x, float lo, float hi) {
    return (x < lo) ? lo : ((x > hi) ? hi : x);
}

/* Fast exp2f(x) for semitone/cent pitch offsets x in [-6, +6] octaves */
static inline float fast_exp2f(float x) {
    x = clampf(x, -6.0f, 6.0f);
    int i = (int)floorf(x);
    float f = x - (float)i;
    float p = 1.0f + f * (0.69314718f + f * (0.2402265f + f * 0.0555041f));
    union { uint32_t u; float fl; } scale;
    scale.u = (uint32_t)((i + 127) << 23);
    return p * scale.fl;
}

/* 2nd-order Polynomial Band-Limited Step (PolyBLEP) residual around a discontinuity at t = 0 / 1 */
static inline float poly_blep(float t, float dt) {
    if (dt <= 1.0e-7f) return 0.0f;
    if (t < dt) {
        t /= dt;
        return t + t - t * t - 1.0f;
    } else if (t > 1.0f - dt) {
        t = (t - 1.0f) / dt;
        return t * t + t + t + 1.0f;
    }
    return 0.0f;
}

void alpha_osc_init(alpha_osc_t *osc) {
    if (!osc) return;
    osc->frequency       = 220.0f;
    osc->phase           = 0.0f;
    osc->phase_increment = 220.0f * ALPHA_INV_FS;
    osc->level           = 0.85f;
    osc->detune          = 0.0f;
    osc->pulse_width     = 0.50f;
    osc->phase_offset    = 0.0f;
    osc->tri_state       = 0.0f;
    osc->pitch_semi      = 0;
    osc->fine_cents      = 0;
    osc->waveform        = ALPHA_WAVE_SAW;
}

void alpha_osc_reset(alpha_osc_t *osc) {
    if (!osc) return;
    osc->phase     = osc->phase_offset - floorf(osc->phase_offset);
    osc->tri_state = 0.0f;
}

void alpha_osc_set_freq(alpha_osc_t *osc, float base_freq_hz, float extra_cents) {
    if (!osc) return;
    float total_semi = (float)osc->pitch_semi + ((float)osc->fine_cents + osc->detune + extra_cents) * 0.01f;
    float freq = base_freq_hz * fast_exp2f(total_semi * (1.0f / 12.0f));
    /* Keep oscillator fundamental safely below Nyquist / 2 (16 kHz) */
    freq = clampf(freq, 20.0f, 16000.0f);
    osc->frequency       = freq;
    osc->phase_increment = freq * ALPHA_INV_FS;
}

float alpha_osc_step(alpha_osc_t *osc, float pwm_mod) {
    float dt = osc->phase_increment;
    float t  = osc->phase;
    float y  = 0.0f;

    switch (osc->waveform) {
        case ALPHA_WAVE_SAW: {
            /* Naive saw in [-1, +1] minus PolyBLEP step residual */
            y = 2.0f * t - 1.0f;
            y -= poly_blep(t, dt);
            break;
        }
        case ALPHA_WAVE_SQUARE: {
            float pw = clampf(osc->pulse_width + pwm_mod, 0.05f, 0.95f);
            /* Zero-mean pulse wave: subtract exact DC bias (2*pw - 1) so PWM never shifts DC */
            y = (t < pw) ? 1.0f : -1.0f;
            y += poly_blep(t, dt);
            float t2 = t - pw;
            if (t2 < 0.0f) t2 += 1.0f;
            y -= poly_blep(t2, dt);
            y -= (2.0f * pw - 1.0f);
            break;
        }
        case ALPHA_WAVE_TRIANGLE:
        default: {
            /* Band-limited triangle generated by integrating a 50% PolyBLEP square wave
             * with frequency-scaled step (4 * dt) and a 0.999 leaky integrator to prevent DC drift. */
            float sq = (t < 0.5f) ? 1.0f : -1.0f;
            sq += poly_blep(t, dt);
            float t2 = t - 0.5f;
            if (t2 < 0.0f) t2 += 1.0f;
            sq -= poly_blep(t2, dt);
            osc->tri_state = 0.999f * osc->tri_state + (4.0f * dt) * sq;
            osc->tri_state = clampf(osc->tri_state, -1.1f, 1.1f);
            y = osc->tri_state;
            break;
        }
    }

    t += dt;
    if (t >= 1.0f) t -= 1.0f;
    osc->phase = t;
    return y * osc->level;
}

void alpha_osc_engine_init(alpha_osc_engine_t *eng) {
    if (!eng) return;
    alpha_osc_init(&eng->osc_a);
    alpha_osc_init(&eng->osc_b);
    eng->osc_a.waveform   = ALPHA_WAVE_SAW;
    eng->osc_a.pitch_semi = 0;
    eng->osc_a.level      = 0.85f;

    eng->osc_b.waveform   = ALPHA_WAVE_SAW;
    eng->osc_b.pitch_semi = 12; /* +1 octave default GR-inspired harmonic layer */
    eng->osc_b.detune     = 8.0f;
    eng->osc_b.level      = 0.65f;

    eng->sub_phase    = 0.0f;
    eng->sub_level    = 0.45f;
    eng->sub_mode     = ALPHA_SUB_OFF;
    eng->osc_mix      = 0.45f;
    eng->cur_amp_gate = 0.0f;
    eng->dc_x1        = 0.0f;
    eng->dc_y1        = 0.0f;
}

void alpha_osc_engine_reset(alpha_osc_engine_t *eng) {
    if (!eng) return;
    alpha_osc_reset(&eng->osc_a);
    alpha_osc_reset(&eng->osc_b);
    eng->sub_phase    = 0.0f;
    eng->cur_amp_gate = 0.0f;
    eng->dc_x1        = 0.0f;
    eng->dc_y1        = 0.0f;
}

void alpha_osc_engine_process_block(alpha_osc_engine_t *eng, float base_freq_hz,
                                    int active_gate, float pitch_mod_cents,
                                    float pwm_mod, float amp_mod,
                                    float *out_buf, int n) {
    if (!eng || !out_buf || n <= 0) return;

    /* Update oscillator frequencies continuously while preserving phase */
    alpha_osc_set_freq(&eng->osc_a, base_freq_hz, -0.5f * eng->osc_b.detune + pitch_mod_cents);
    alpha_osc_set_freq(&eng->osc_b, base_freq_hz, +0.5f * eng->osc_b.detune + pitch_mod_cents);

    float sub_mult = (eng->sub_mode == ALPHA_SUB_OCT1) ? 0.5f : ((eng->sub_mode == ALPHA_SUB_OCT2) ? 0.25f : 0.0f);
    float sub_dt   = (base_freq_hz * sub_mult) * ALPHA_INV_FS;
    sub_dt = clampf(sub_dt, 0.0f, 0.40f);

    /* Balanced A/B mix weights */
    float mix = clampf(eng->osc_mix, 0.0f, 1.0f);
    float wa  = (1.0f - mix) * 1.4142f;
    float wb  = mix * 1.4142f;
    if (wa > 1.0f) wa = 1.0f;
    if (wb > 1.0f) wb = 1.0f;

    float amp_scale = clampf(1.0f + amp_mod, 0.0f, 1.5f);
    /* Smooth activation/deactivation ramp (~3 ms attack, ~8 ms release) for click-free note gating */
    const float gate_att = 0.008f;
    const float gate_rel = 0.003f;
    float target_gate = active_gate ? 1.0f : 0.0f;

    for (int i = 0; i < n; i++) {
        if (target_gate > eng->cur_amp_gate) {
            eng->cur_amp_gate += gate_att * (target_gate - eng->cur_amp_gate);
        } else {
            eng->cur_amp_gate += gate_rel * (target_gate - eng->cur_amp_gate);
        }
        if (eng->cur_amp_gate < 1.0e-5f && !active_gate) {
            eng->cur_amp_gate = 0.0f;
            out_buf[i] = 0.0f;
            continue;
        }

        float ya = alpha_osc_step(&eng->osc_a, pwm_mod);
        float yb = alpha_osc_step(&eng->osc_b, pwm_mod);

        float y_sub = 0.0f;
        if (eng->sub_mode != ALPHA_SUB_OFF && sub_dt > 0.0f) {
            float st = eng->sub_phase;
            /* Band-limited PolyBLEP square sub-oscillator */
            y_sub = (st < 0.5f) ? 1.0f : -1.0f;
            y_sub += poly_blep(st, sub_dt);
            float st2 = st - 0.5f;
            if (st2 < 0.0f) st2 += 1.0f;
            y_sub -= poly_blep(st2, sub_dt);
            st += sub_dt;
            if (st >= 1.0f) st -= 1.0f;
            eng->sub_phase = st;
            y_sub *= eng->sub_level;
        }

        /* Controlled oscillator summing (-6 dB internal summing pad so A+B+Sub never clips) */
        float sum = (wa * ya + wb * yb + 0.65f * y_sub) * 0.55f;
        sum *= eng->cur_amp_gate * amp_scale;

        /* 15 Hz DC blocker */
        float dc_y = sum - eng->dc_x1 + 0.9978f * eng->dc_y1;
        eng->dc_x1 = sum;
        eng->dc_y1 = dc_y;
        out_buf[i] = dc_y;
    }
}
