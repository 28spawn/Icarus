/* custom-fw/src/effects/icarus/icarus_osc.c — Band-Limited Dual Oscillator + Sub Oscillator Engine */
#include "icarus_osc.h"
#include "pa_config.h"
#include <math.h>
#include "icarus_fastmath.h"

#define ICARUS_FS     ((float)PA_SAMPLE_RATE)
#define ICARUS_INV_FS (1.0f / (float)PA_SAMPLE_RATE)
#define ICARUS_OSC_MAX_BLOCK 64      /* the synth's block (PA_BLOCK_N); the engine works in chunks of at most this many samples */

static inline float clampf(float x, float lo, float hi) {
    return (x < lo) ? lo : ((x > hi) ? hi : x);
}

/* Fast exp2f(x) for semitone/cent pitch offsets x in [-6, +6] octaves */
static inline float fast_exp2f(float x) {
    x = clampf(x, -6.0f, 6.0f);
    int i = (int)floorf(x);
    float f = x - (float)i;
    float p = 1.0f + f * (0.69314718f + f * (0.2402265f + f * 0.0555041f));
    union { uint32_t u; float fl; } scale;
    scale.u = (uint32_t)((i + 127) << 23);
    return p * scale.fl;
}

/* 2nd-order Polynomial Band-Limited Step (PolyBLEP) residual around a discontinuity at t = 0 / 1 */
static inline float poly_blep(float t, float dt) {
    if (dt <= 1.0e-7f) return 0.0f;
    if (t < dt) {
        t /= dt;
        return t + t - t * t - 1.0f;
    } else if (t > 1.0f - dt) {
        t = (t - 1.0f) / dt;
        return t * t + t + t + 1.0f;
    }
    return 0.0f;
}

void icarus_osc_init(icarus_osc_t *osc) {
    if (!osc) return;
    osc->frequency       = 220.0f;
    osc->phase           = 0.0f;
    osc->phase_increment = 220.0f * ICARUS_INV_FS;
    osc->level           = 0.85f;
    osc->detune          = 0.0f;
    osc->pulse_width     = 0.50f;
    osc->phase_offset    = 0.0f;
    osc->tri_state       = 0.0f;
    osc->pitch_semi      = 0;
    osc->fine_cents      = 0;
    osc->waveform        = ICARUS_WAVE_SAW;
}

void icarus_osc_reset(icarus_osc_t *osc) {
    if (!osc) return;
    osc->phase     = osc->phase_offset - floorf(osc->phase_offset);
    osc->tri_state = 0.0f;
}

void icarus_osc_set_freq(icarus_osc_t *osc, float base_freq_hz, float extra_cents) {
    if (!osc) return;
    float total_semi = (float)osc->pitch_semi + ((float)osc->fine_cents + osc->detune + extra_cents) * 0.01f;
    float freq = base_freq_hz * fast_exp2f(total_semi * (1.0f / 12.0f));
    /* Keep oscillator fundamental safely below Nyquist / 2 (16 kHz) */
    freq = clampf(freq, 20.0f, 16000.0f);
    osc->frequency       = freq;
    osc->phase_increment = freq * ICARUS_INV_FS;
}

float icarus_osc_step(icarus_osc_t *osc, float pwm_mod) {
    float dt = osc->phase_increment;
    float t  = osc->phase;
    float y  = 0.0f;

    switch (osc->waveform) {
        case ICARUS_WAVE_SAW: {
            /* Naive saw in [-1, +1] minus PolyBLEP step residual */
            y = 2.0f * t - 1.0f;
            y -= poly_blep(t, dt);
            break;
        }
        case ICARUS_WAVE_SQUARE: {
            float pw = clampf(osc->pulse_width + pwm_mod, 0.05f, 0.95f);
            /* Zero-mean pulse wave: subtract exact DC bias (2*pw - 1) so PWM never shifts DC */
            y = (t < pw) ? 1.0f : -1.0f;
            y += poly_blep(t, dt);
            float t2 = t - pw;
            if (t2 < 0.0f) t2 += 1.0f;
            y -= poly_blep(t2, dt);
            y -= (2.0f * pw - 1.0f);
            break;
        }
        case ICARUS_WAVE_TRIANGLE:
        default: {
            /* Band-limited triangle generated by integrating a 50% PolyBLEP square wave
             * with frequency-scaled step (4 * dt) and a 0.999 leaky integrator to prevent DC drift. */
            float sq = (t < 0.5f) ? 1.0f : -1.0f;
            sq += poly_blep(t, dt);
            float t2 = t - 0.5f;
            if (t2 < 0.0f) t2 += 1.0f;
            sq -= poly_blep(t2, dt);
            osc->tri_state = 0.999f * osc->tri_state + (4.0f * dt) * sq;
            osc->tri_state = clampf(osc->tri_state, -1.1f, 1.1f);
            y = osc->tri_state;
            break;
        }
    }

    t += dt;
    if (t >= 1.0f) t -= 1.0f;
    osc->phase = t;
    return y * osc->level;
}

void icarus_osc_engine_init(icarus_osc_engine_t *eng) {
    if (!eng) return;
    icarus_osc_init(&eng->osc_a);
    icarus_osc_init(&eng->osc_b);
    eng->osc_a.waveform   = ICARUS_WAVE_SAW;
    eng->osc_a.pitch_semi = 0;
    eng->osc_a.level      = 0.85f;

    eng->osc_b.waveform   = ICARUS_WAVE_SAW;
    eng->osc_b.pitch_semi = 12; /* +1 octave default GR-inspired harmonic layer */
    eng->osc_b.detune     = 8.0f;
    eng->osc_b.level      = 0.65f;

    eng->sub_phase    = 0.0f;
    eng->sub_level    = 0.45f;
    eng->sub_mode     = ICARUS_SUB_OFF;
    eng->osc_mix      = 0.45f;
    eng->cur_amp_gate = 0.0f;
    eng->dc_x1        = 0.0f;
    eng->dc_y1        = 0.0f;
}

void icarus_osc_engine_reset(icarus_osc_engine_t *eng) {
    if (!eng) return;
    icarus_osc_reset(&eng->osc_a);
    icarus_osc_reset(&eng->osc_b);
    eng->sub_phase    = 0.0f;
    eng->cur_amp_gate = 0.0f;
    eng->dc_x1        = 0.0f;
    eng->dc_y1        = 0.0f;
}

/* PolyBLEP residual with the division by dt hoisted: inv_dt = 1 / dt, computed once per block. `bdt` is dt, or -1 when dt is too small to correct
 * (both tests below then fail, as the original returned 0). */
static inline float blep(float t, float bdt, float inv_dt) {
    if (t < bdt) {
        t *= inv_dt;
        return t + t - t * t - 1.0f;
    } else if (t > 1.0f - bdt) {
        t = (t - 1.0f) * inv_dt;
        return t * t + t + t + 1.0f;
    }
    return 0.0f;
}

/* One band-limited oscillator over a whole block: phase (and the triangle's integrator) in locals, the waveform switch outside the loop. Same
 * maths as icarus_osc_step, which stays for the unit tests. */
static void osc_block(icarus_osc_t *o, float pwm_mod, float *out, int n) {
    float t = o->phase;
    const float dt  = o->phase_increment;
    const float bdt = (dt > 1.0e-7f) ? dt : -1.0f;
    const float inv = (dt > 1.0e-7f) ? 1.0f / dt : 0.0f;
    const float lvl = o->level;

    switch (o->waveform) {
        case ICARUS_WAVE_SAW:
            for (int i = 0; i < n; i++) {
                out[i] = (2.0f * t - 1.0f - blep(t, bdt, inv)) * lvl;
                t += dt;
                if (t >= 1.0f) t -= 1.0f;
            }
            break;
        case ICARUS_WAVE_SQUARE: {
            const float pw   = clampf(o->pulse_width + pwm_mod, 0.05f, 0.95f);
            const float bias = 2.0f * pw - 1.0f;                 /* zero-mean pulse: subtract the exact DC bias */
            for (int i = 0; i < n; i++) {
                float y = (t < pw) ? 1.0f : -1.0f;
                y += blep(t, bdt, inv);
                float t2 = t - pw;
                if (t2 < 0.0f) t2 += 1.0f;
                y -= blep(t2, bdt, inv);
                out[i] = (y - bias) * lvl;
                t += dt;
                if (t >= 1.0f) t -= 1.0f;
            }
            break;
        }
        case ICARUS_WAVE_TRIANGLE:
        default: {
            float tri = o->tri_state;
            const float k4 = 4.0f * dt;
            for (int i = 0; i < n; i++) {
                float sq = (t < 0.5f) ? 1.0f : -1.0f;
                sq += blep(t, bdt, inv);
                float t2 = t - 0.5f;
                if (t2 < 0.0f) t2 += 1.0f;
                sq -= blep(t2, bdt, inv);
                tri = 0.999f * tri + k4 * sq;
                tri = (tri > 1.1f) ? 1.1f : ((tri < -1.1f) ? -1.1f : tri);
                out[i] = tri * lvl;
                t += dt;
                if (t >= 1.0f) t -= 1.0f;
            }
            o->tri_state = tri;
            break;
        }
    }
    o->phase = t;
}

void icarus_osc_engine_process_block(icarus_osc_engine_t *eng, float base_freq_hz,
                                    int active_gate, float pitch_mod_cents,
                                    float pwm_mod, float amp_mod,
                                    float *out_buf, int n) {
    if (!eng || !out_buf || n <= 0) return;

    /* Voice fully off and nothing asked for: the block is silence (the oscillators were not stepped for those samples before either) */
    if (!active_gate && eng->cur_amp_gate < 1.0e-5f) {
        eng->cur_amp_gate = 0.0f;
        for (int i = 0; i < n; i++) out_buf[i] = 0.0f;
        return;
    }

    /* Update oscillator frequencies continuously while preserving phase */
    icarus_osc_set_freq(&eng->osc_a, base_freq_hz, -0.5f * eng->osc_b.detune - 0.5f * eng->drift_diff_cents + pitch_mod_cents);
    icarus_osc_set_freq(&eng->osc_b, base_freq_hz, +0.5f * eng->osc_b.detune + 0.5f * eng->drift_diff_cents + pitch_mod_cents);

    float sub_mult = (eng->sub_mode == ICARUS_SUB_OCT1) ? 0.5f : ((eng->sub_mode == ICARUS_SUB_OCT2) ? 0.25f : 0.0f);
    float sub_dt   = (base_freq_hz * sub_mult) * ICARUS_INV_FS;
    sub_dt = clampf(sub_dt, 0.0f, 0.40f);
    const int sub_on = (eng->sub_mode != ICARUS_SUB_OFF && sub_dt > 0.0f);

    /* Balanced A/B mix weights */
    float mix = clampf(eng->osc_mix, 0.0f, 1.0f);
    float wa  = (1.0f - mix) * 1.4142f;
    float wb  = mix * 1.4142f;
    if (wa > 1.0f) wa = 1.0f;
    if (wb > 1.0f) wb = 1.0f;

    /* THE AMPLITUDE ENVELOPE. amp_mod used to be added to 1.0 (clamp(1 + env, 0, 1.5)), so the voice never went below full level: the ADSR (attack, decay, sustain, release) and the pick velocity only
     * moved it between 1.0 and 1.5, and a soft note sounded as loud as a hard one (captured DI: level-vs-input correlation about 0, 2-3 dB of dynamic range from 11 dB played). The envelope IS the
     * amplitude now. The gain of 1.7 keeps a full-velocity sustained note at about the level the old formula gave (ADSR x 0.65 x velocity peaks near 0.65 -> 1.1). */
    float amp_scale = clampf(amp_mod * 1.7f, 0.0f, 1.5f);

    float ya[ICARUS_OSC_MAX_BLOCK], yb[ICARUS_OSC_MAX_BLOCK], ys[ICARUS_OSC_MAX_BLOCK];
    const int m = (n > ICARUS_OSC_MAX_BLOCK) ? ICARUS_OSC_MAX_BLOCK : n;
    osc_block(&eng->osc_a, pwm_mod, ya, m);
    osc_block(&eng->osc_b, pwm_mod, yb, m);
    if (sub_on) {
        float st = eng->sub_phase;
        const float inv = 1.0f / sub_dt;
        const float k   = 0.65f * eng->sub_level;
        for (int i = 0; i < m; i++) {                            /* band-limited PolyBLEP square sub-oscillator */
            float y = (st < 0.5f) ? 1.0f : -1.0f;
            y += blep(st, sub_dt, inv);
            float st2 = st - 0.5f;
            if (st2 < 0.0f) st2 += 1.0f;
            y -= blep(st2, sub_dt, inv);
            ys[i] = y * k;
            st += sub_dt;
            if (st >= 1.0f) st -= 1.0f;
        }
        eng->sub_phase = st;
    }

    /* Smooth activation/deactivation ramp (~3 ms attack, ~8 ms release) for click-free note gating, the -6 dB summing pad, the 15 Hz DC blocker */
    const float gate_att = 0.008f;
    const float gate_rel = 0.003f;
    const float target_gate = active_gate ? 1.0f : 0.0f;
    float gate = eng->cur_amp_gate;
    float dc_x1 = eng->dc_x1, dc_y1 = eng->dc_y1;
    for (int i = 0; i < m; i++) {
        gate += ((target_gate > gate) ? gate_att : gate_rel) * (target_gate - gate);
        if (gate < 1.0e-5f && !active_gate) {
            gate = 0.0f;
            out_buf[i] = 0.0f;
            continue;
        }
        float sum = wa * ya[i] + wb * yb[i];
        if (sub_on) sum += ys[i];                                /* ys already carries the 0.65 and the sub level */
        sum *= 0.55f * gate * amp_scale;
        const float dc_y = sum - dc_x1 + 0.9978f * dc_y1;
        dc_x1 = sum;
        dc_y1 = dc_y;
        out_buf[i] = dc_y;
    }
    eng->cur_amp_gate = gate;
    eng->dc_x1 = dc_x1;
    eng->dc_y1 = dc_y1;
}
